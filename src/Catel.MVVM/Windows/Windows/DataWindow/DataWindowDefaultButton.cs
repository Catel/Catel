namespace Catel.Windows;

/// <summary>
/// Available default buttons on the data window mode.
/// </summary>
public enum DataWindowDefaultButton
{
    Default = OK,

    /// <summary>
    /// No button.
    /// </summary>
    None = 0,

    /// <summary>
    /// OK button.
    /// </summary>
    OK = 1,

    /// <summary>
    /// Apply button.
    /// </summary>
    Apply = 2,

    /// <summary>
    /// Close button.
    /// </summary>
    Close = 3,
}
